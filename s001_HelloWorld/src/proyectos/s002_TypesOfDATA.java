package proyectos;

public class s002_TypesOfDATA {
	
	public static void main(String[] args) {
		
		byte miByte = 15;
		short productos = 15000;
		int edad = 30;
		double distasncia = 125.6789;
		String nombre = "Carlos";
		char nota = 'S';
		boolean aprobado = true;
		
		System.out.println("Número de Alumnos: " + miByte);
		System.out.println("Productos disponibles: " + productos);
		System.out.println("Edad del cliente: " + edad);
		System.out.println("Distancia recorrida: " + distasncia + " km");
		System.out.println("Mi nombre es: " + nombre);
		System.out.println("Nota del alumno: " + nota);
		System.out.println("¿Ha aprobado el alumno?\n" + aprobado);
		
	}

}
